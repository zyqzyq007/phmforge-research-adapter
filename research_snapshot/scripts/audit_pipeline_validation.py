"""Audit cached complete-program validation without fitting or predicting."""
import argparse
import hashlib
import json
from pathlib import Path
import time
import numpy as np


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def run(root):
    begin = time.monotonic()
    cfg = json.loads((root/'PROTOCOL376.json').read_text())
    assert not (root/'RESULT376.json').exists()
    bindings = []
    def bind(path):
        bindings.append(dict(path=str(path), bytes=path.stat().st_size, sha256=sha(path)))
        return path
    src = {k: Path(v['path']) for k, v in cfg['sources'].items()}
    for k, folder in src.items():
        assert sha(bind(folder/'SOURCE_MANIFEST.json')) == cfg['sources'][k]['manifest_sha256']
    source = src['source']
    parent = source/'subjects/ordinary_2/programs/p01'
    jobs = json.loads(bind(source/'JOBS366.json').read_text())
    report = json.loads(bind(parent/'REPORT.json').read_text())
    for relative, digest in report['artifacts'].items():
        assert sha(bind(parent/relative)) == digest
    with np.load(bind(source/'private_inputs/training_queries_private.npz'), allow_pickle=False) as z:
        cells = z['groups'].tolist()
        ids = z['sample_ids'].tolist()
    with np.load(bind(src['profiles']/'PROFILES371.npz'), allow_pickle=False) as z:
        assert z['train_groups'].tolist() == cells
        column = z['programs'].tolist().index('ordinary_2__p01')
        cached = z['cv_prediction'][:, column]
    fold_of = {g: name for name, job in jobs.items() if name != 'full' for g in job['heldout_cells']}
    assert set(fold_of) == set(cells) and len(cells) == 47
    folds = []
    for name, job in jobs.items():
        if name == 'full':
            continue
        fit, held = set(job['fitting_cells']), set(job['heldout_cells'])
        assert not fit & held and fit | held == set(cells)
        with np.load(bind(parent/name/'train.npz'), allow_pickle=False) as z:
            assert set(z['groups'].tolist()) == fit
            total_rows = len(z['groups'])
            near_rows = int(np.sum((z['age'] >= 458) & (z['age'] <= 538)))
        with np.load(bind(parent/name/'check/PREDICTIONS.npz'), allow_pickle=False) as z:
            observed = dict(zip(z['sample_ids'].tolist(), z['prediction'].tolist()))
        index = [i for i, g in enumerate(cells) if g in held]
        np.testing.assert_allclose([observed[ids[i]] for i in index], cached[index], rtol=0, atol=0)
        # Global OOF residuals for outer-training cells were generated by
        # models trained on the proposed outer-validation cells.
        contaminated = [g for g in fit if held & set(jobs[fold_of[g]]['fitting_cells'])]
        folds.append(dict(fold=name, fitting_cells=sorted(fit), heldout_cells=sorted(held),
            train_rows=total_rows, actual_parent_near_rows=near_rows,
            cached_parent_heldout_rows=len(index),
            outer_training_global_oof_rows_with_validation_label_ancestry=len(contaminated),
            naive_global_oof_rows=len(fit)))
    capacity = json.loads(bind(src['capacity']/'FIT_EVENTS373.json').read_text())
    selected = [e for e in capacity if e['spec'] == 'raw_input__mixed_54__residual__ridge10']
    partial = json.loads(bind(src['partial']/'FIT_EVENTS374.json').read_text())
    assert len(selected) == 8 and len(partial) == 64
    for e in selected + partial:
        assert set(e['fitting_source_cells']) == set(cells)
        assert e['held'] not in e['fitting_development_cells']
    for e in partial:
        assert not set(e['fitting_development_cells']) & set(e['query_development_cells'])
    result = dict(id='A376', passed=True, elapsed_seconds=time.monotonic()-begin,
        qualified_parent_only_source_rows=47, existing_qualified_complete_pipeline_source_rows=0,
        selected_outer_corrections_with_all47_source_labels=len(selected),
        inner_corrections_with_all47_source_labels=len(partial),
        honest_existing_development_loo_checks=sum(e['kind'] == 'loo' for e in partial),
        existing_development_split_checks=sum(e['kind'] == 'split' for e in partial),
        development_validation_remains_valid=True, folds=folds,
        new_fits=0, new_predictions=0, new_LLM_calls=0, final22_opened=False, A33872_opened=False,
        causal_claim='Provenance risk of reusing source rows as complete-program validation; not evidence that any reported dev score leaked or that validation absence caused errors.',
        next_admission='Nested source cross-fitting with fixed parent code is feasible. Reuse three outer parent models; train three inner parents per outer fold, and exclude each outer fold from both stages and all label-derived ancestors. Conventional validation control, no novelty claim.',
        new_inner_parent_fits_required=9, proposed_complete_pipeline_correction_fits=24,
        bindings=bindings)
    assert result['elapsed_seconds'] < cfg['budget']['wall_seconds']
    (root/'RESULT376.json').write_text(json.dumps(result, indent=2)+'\n')
    (root/'TERMINAL376.json').write_text(json.dumps(dict(exit_code=0, elapsed_seconds=result['elapsed_seconds']))+'\n')
    print(json.dumps({k:v for k,v in result.items() if k not in ['bindings','folds']}))


if __name__ == '__main__':
    p=argparse.ArgumentParser(); p.add_argument('--run', type=Path, required=True)
    run(p.parse_args().run.resolve())
